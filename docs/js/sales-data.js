// ── Smart Aggregation by Product ─────────────────────
function getAggregatedSales(opts = {}) {
  const cat     = (opts.category || '').toLowerCase().trim();
  const brand   = (opts.brand || '').toLowerCase().trim();
  const product = (opts.product || '').toLowerCase().trim();
  const region  = (opts.region || '').toLowerCase().trim();

  const filtered = REGIONAL_SALES.filter(r => {
    if (cat && cat !== 'all' && r.category.toLowerCase() !== cat) return false;
    if (brand && brand !== 'all' && r.brand.toLowerCase() !== brand) return false;
    if (product && product !== 'all' && !r.product.toLowerCase().includes(product)) return false;
    if (region && region !== 'all' && r.region.toLowerCase() !== region) return false;
    return true;
  });

  // Group by Product
  const prodMap = {};
  filtered.forEach(r => {
    if (!prodMap[r.product]) {
      prodMap[r.product] = {
        name: r.product,
        category: r.category,
        brand: r.brand,
        revenue: 0,
        units: 0,
        stock: 0,
        _ratingSum: 0,
        _discountSum: 0,
        _count: 0
      };
    }
    const item = prodMap[r.product];
    item.revenue += r.revenue;
    item.units += r.units;
    item.stock += r.stock;
    item._ratingSum += r.rating * (r.units || 1);
    item._discountSum += r.discount * (r.units || 1);
    item._count += (r.units || 1);
  });

  return Object.values(prodMap).map(p => ({
    name: p.name,
    category: p.category,
    brand: p.brand,
    revenue: p.revenue,
    units: p.units,
    stock: p.stock,
    rating: p._count > 0 ? (p._ratingSum / p._count) : 4.5,
    discount: p._count > 0 ? (p._discountSum / p._count) : 5.0
  })).sort((a, b) => b.revenue - a.revenue);
}

// ── Smart Aggregation by Brand ───────────────────────
function getAggregatedBrands(opts = {}) {
  const cat    = (opts.category || '').toLowerCase().trim();
  const region = (opts.region || '').toLowerCase().trim();

  const filtered = REGIONAL_SALES.filter(r => {
    if (cat && cat !== 'all' && r.category.toLowerCase() !== cat) return false;
    if (region && region !== 'all' && r.region.toLowerCase() !== region) return false;
    return true;
  });

  const brandMap = {};
  filtered.forEach(r => {
    if (!brandMap[r.brand]) {
      brandMap[r.brand] = {
        brand: r.brand,
        revenue: 0,
        units: 0,
        stock: 0,
        _ratingSum: 0,
        _count: 0,
        productSet: new Set()
      };
    }
    const b = brandMap[r.brand];
    b.revenue += r.revenue;
    b.units += r.units;
    b.stock += r.stock;
    b._ratingSum += r.rating * (r.units || 1);
    b._count += (r.units || 1);
    b.productSet.add(r.product);
  });

  return Object.values(brandMap).map(b => ({
    brand: b.brand,
    revenue: b.revenue,
    units: b.units,
    stock: b.stock,
    avgRating: b._count > 0 ? (b._ratingSum / b._count) : 4.5,
    count: b.productSet.size
  })).sort((a, b) => b.revenue - a.revenue);
}

// ── Number & Currency Formatting ─────────────────────
function fmtRevenue(r) {
  if (r >= 1e9) return (r / 1e9).toFixed(2) + 'B';
  if (r >= 1e6) return (r / 1e6).toFixed(1) + 'M';
  if (r >= 1e3) return (r / 1e3).toFixed(0) + 'K';
  return Math.round(r).toLocaleString();
}
function fmtPKR(r) { return 'PKR ' + fmtRevenue(r); }

